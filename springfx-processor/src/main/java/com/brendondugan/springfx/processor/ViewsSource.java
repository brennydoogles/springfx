package com.brendondugan.springfx.processor;

import java.util.Comparator;
import java.util.List;

/** Writes the source of the generated {@code Views} enum (ADR-0004). */
class ViewsSource {

    static final String SIMPLE_NAME = "Views";
    static final String VIEW_NAME_INTERFACE = "com.brendondugan.springfx.ViewName";

    private ViewsSource() {
    }

    /**
     * @param pkg the package, empty for the unnamed package
     * @param controllers the module's Controllers, each with a valid, unique View Name
     * @param generatedAnnotation whether {@code javax.annotation.processing.Generated} is available
     */
    static String of(String pkg, List<ControllerDeclaration> controllers, boolean generatedAnnotation) {
        StringBuilder out = new StringBuilder();
        if (!pkg.isEmpty()) {
            out.append("package ").append(pkg).append(";\n\n");
        }
        out.append("""
                /**
                 * The Views of this module, by View Name. Generated by springfx-processor from each
                 * Controller's {@code @SpringFXController(viewName)}; open one with
                 * {@code windows.open(Views.NAME)}.
                 */
                """);
        if (generatedAnnotation) {
            out.append("@javax.annotation.processing.Generated(\"").append(SpringFXProcessor.class.getName())
                    .append("\")\n");
        }
        out.append("public enum ").append(SIMPLE_NAME).append(" implements ").append(VIEW_NAME_INTERFACE)
                .append(" {\n\n");
        controllers.stream()
                .sorted(Comparator.comparing(ControllerDeclaration::viewName))
                .forEach(controller -> out
                        .append("    /** {@link ").append(controller.name()).append("} */\n")
                        .append("    ").append(controller.viewName())
                        .append("(").append(controller.name()).append(".class),\n\n"));
        out.append("""
                    ;

                    private final Class<?> controllerType;

                    Views(Class<?> controllerType) {
                        this.controllerType = controllerType;
                    }

                    @Override
                    public Class<?> controllerType() {
                        return controllerType;
                    }
                }
                """);
        return out.toString();
    }
}
